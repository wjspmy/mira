export function filterEmoji(query: string): Array<{ label: string; items: string[] }> {
  const q = query.trim();
  if (!q) return EMOJI_GROUPS;
  // 中文名简单映射
  const aliases: Record<string, string[]> = {
    笑: ["😄", "😂", "🤣", "😀"],
    哭: ["😢", "😭"],
    心: ["❤️", "💙", "💚", "💔"],
    火: ["🔥"],
    赞: ["👍", "👌"],
    ok: ["👌", "✅"],
    star: ["⭐", "🌟"],
  };
  const hit = aliases[q.toLowerCase()] || aliases[q] || [];
  if (hit.length) return [{ label: "匹配", items: hit }];
  return [{ label: "匹配", items: [q] }];
}
